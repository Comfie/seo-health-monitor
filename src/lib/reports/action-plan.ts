import { priorityBucket } from "@/lib/audit/issues";
import { CATEGORY_LABELS, type Category } from "@/lib/audit/types";

export interface IssueLike {
  issueKey: string;
  checkId: string;
  category: string;
  severity: string;
  title: string;
  url: string;
  evidence: string[];
  why: string;
  fix: string;
  implementation: string;
  benefit: string;
  impact: number;
  confidence: string;
  effort: string;
  priorityScore: number;
}

export interface ActionItem {
  id: string;
  checkId: string;
  category: string;
  title: string;
  severity: string;
  priorityScore: number;
  bucket: ReturnType<typeof priorityBucket>;
  confidence: string;
  effort: string;
  why: string;
  fix: string;
  implementation: string;
  benefit: string;
  issues: IssueLike[];
}

const SEVERITY_RANK: Record<string, number> = { critical: 0, high: 1, medium: 2, low: 3 };

/** Groups per-URL issues into one task per problem type, ordered by priority. */
export function buildActionPlan(issues: IssueLike[]): ActionItem[] {
  const groups = new Map<string, ActionItem>();
  for (const issue of issues) {
    const id = `${issue.checkId}|${issue.title}`;
    const existing = groups.get(id);
    if (!existing) {
      groups.set(id, {
        id,
        checkId: issue.checkId,
        category: issue.category,
        title: issue.title,
        severity: issue.severity,
        priorityScore: issue.priorityScore,
        bucket: priorityBucket(issue.priorityScore),
        confidence: issue.confidence,
        effort: issue.effort,
        why: issue.why,
        fix: issue.fix,
        implementation: issue.implementation,
        benefit: issue.benefit,
        issues: [issue],
      });
      continue;
    }
    existing.issues.push(issue);
    if (issue.priorityScore > existing.priorityScore) {
      existing.priorityScore = issue.priorityScore;
      existing.bucket = priorityBucket(issue.priorityScore);
    }
    if (SEVERITY_RANK[issue.severity] < SEVERITY_RANK[existing.severity]) existing.severity = issue.severity;
  }
  return [...groups.values()].sort(
    (a, b) => b.priorityScore - a.priorityScore || SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity] || b.issues.length - a.issues.length,
  );
}

export function categoryLabel(category: string): string {
  return CATEGORY_LABELS[category as Category] ?? category;
}

/**
 * Markdown task list for an AI coding tool or a developer: one task per problem with
 * the exact URLs, evidence and implementation guidance.
 */
export function buildDeveloperTasks(siteUrl: string, auditDate: Date | null, issues: IssueLike[]): string {
  const plan = buildActionPlan(issues);
  const lines: string[] = [
    `# SEO fix tasks for ${siteUrl}`,
    "",
    `Generated by SEO Health Monitor from an audit on ${auditDate ? auditDate.toISOString().slice(0, 10) : "unknown date"}.`,
    "Every task below comes from a measured finding. Fix in the order listed; verify each fix by re-running the audit.",
    "",
  ];
  plan.forEach((item, index) => {
    lines.push(`## ${index + 1}. ${item.title}`);
    lines.push("");
    lines.push(`- **Priority:** ${item.bucket} (score ${item.priorityScore}) · **Severity:** ${item.severity} · **Category:** ${categoryLabel(item.category)} · **Effort:** ${item.effort} · **Confidence:** ${item.confidence}`);
    lines.push(`- **Why it matters:** ${item.why}`);
    lines.push(`- **Fix:** ${item.fix}`);
    lines.push("");
    lines.push("**Implementation:**");
    lines.push("");
    lines.push(item.implementation.includes("\n") ? "```\n" + item.implementation + "\n```" : item.implementation);
    lines.push("");
    lines.push(`**Affected URLs (${item.issues.length}):**`);
    lines.push("");
    for (const issue of item.issues.slice(0, 30)) {
      lines.push(`- [ ] ${issue.url}`);
      for (const ev of issue.evidence.slice(0, 4)) lines.push(`  - ${ev}`);
    }
    if (item.issues.length > 30) lines.push(`- …and ${item.issues.length - 30} more (see the JSON export).`);
    lines.push("");
    lines.push(`**Acceptance check:** re-run the audit and confirm "${item.title}" no longer appears for these URLs.`);
    lines.push("");
  });
  if (!plan.length) lines.push("No issues were found in this audit.");
  return lines.join("\n");
}
